def heat_curve(kind):
    """Return a temperature–time fragment for a 5-panel grid."""
    if kind == 'pure':
        pts = [(0, 10), (2, 40), (4, 40), (6, 80), (8, 80), (9, 95)]
    elif kind == 'mix':
        pts = [(0, 10), (2, 35), (4, 45), (6, 75), (8, 88), (9, 95)]
    elif kind == 'one':
        pts = [(0, 10), (3, 60), (6, 60), (9, 95)]
    elif kind == 'none':
        pts = [(0, 10), (9, 95)]
    elif kind == 'cool':
        pts = [(0, 95), (1, 80), (3, 80), (5, 40), (7, 40), (9, 10)]
    elif kind == 'coolmix':
        pts = [(0, 95), (1, 82), (3, 74), (5, 42), (7, 33), (9, 10)]
    return line_graph([(pts, '', None)], (0, 9), (0, 100), w=190, h=150, xlabel='хугацаа', ylabel='T', grid=False)


