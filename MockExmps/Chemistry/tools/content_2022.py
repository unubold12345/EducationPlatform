def collision(kind, a=('Br', 'Br'), hcolor=False):
    """Ethene-like C=C with an approaching diatomic X–Y in a 160x120 panel."""
    b = ['<circle cx="60" cy="70" r="11" fill="#555"/>', '<circle cx="100" cy="70" r="11" fill="#555"/>',
         line(71, 66, 89, 66, w=2), line(71, 74, 89, 74, w=2)]
    for hx, hy in ((40, 55), (40, 85), (120, 55), (120, 85)):
        b.append(f'<circle cx="{hx}" cy="{hy}" r="6" fill="#ccc" stroke="#111"/>')
    pos = {'perp': ((80, 30), (80, 8)), 'end': ((20, 70), (4, 70)), 'H': ((130, 30), (148, 14)), 'parallel': ((60, 20), (100, 20)),
           'below_far': ((80, 112), (80, 132))}[kind]
    (x1, y1), (x2, y2) = pos
    b += [f'<circle cx="{x1}" cy="{y1}" r="9" fill="#fff" stroke="#111"/>', f'<circle cx="{x2}" cy="{y2}" r="9" fill="#fff" stroke="#111"/>',
          line(x1, y1, x2, y2, w=1.5), text(x1, y1 + 4, a[0], 9), text(x2, y2 + 4, a[1], 9)]
    if kind in ('perp', 'below_far'):
        b.append(line(80, 45 if kind == 'perp' else 98, 80, 60 if kind == 'perp' else 82, w=1, arrow=True))
    return '\n'.join(b)


def collision_grid(order, a):
    return panel_grid([(L, collision(k, a)) for L, k in order], 5, 160, 130, 13)


