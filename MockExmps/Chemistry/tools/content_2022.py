def mbT(kind):
    x0, y0, sx, sy = 30, 105, 32, 70
    b = [line(x0, y0, x0, 20, arrow=True), line(x0, y0, 185, y0, arrow=True)]
    first = mb_points(x0, y0, sx, sy, 1.0, 1.0)
    second = {'right_low': mb_points(x0, y0, sx, sy, 1.35, 0.78), 'left_high': mb_points(x0, y0, sx, sy, 0.75, 1.25),
              'right_high': mb_points(x0, y0, sx, sy, 1.35, 1.25), 'left_low': mb_points(x0, y0, sx, sy, 0.75, 0.75),
              'same_peak': mb_points(x0, y0, sx, sy, 1.0, 0.7)}[kind]
    b += [poly(first), poly(second, dash='4 3'), text(130, 30, 'T₁ —', 10, anchor='start'), text(130, 44, 'T₂ - -', 10, anchor='start')]
    return '\n'.join(b)


