def ptable():
    cells = {(1, 3): 'X', (17, 2): 'Y', (18, 3): 'Q', (2, 4): 'W', (14, 3): 'Z'}
    b = []
    for p in range(1, 5):
        for g in range(1, 19):
            if p == 1 and g not in (1, 18):
                continue
            if p in (2, 3) and 3 <= g <= 12:
                continue
            x, y = 10 + (g - 1) * 28, 10 + (p - 1) * 28
            b.append(rect(x, y, 28, 28, sw=0.8))
            if (g, p) in cells:
                b.append(text(x + 14, y + 19, cells[(g, p)], 14, weight='bold'))
    return svg(530, 130, '\n'.join(b))


