def checks() -> None:
    assert 35 - 17 == 18
    assert 2 * M["H"] + M["S"] + 4 * M["O"] == 98
    assert 2 * 1 + 2 * 6 + 7 * (-2) == 0  # K₂Cr₂O₇ with Cr = +6
    assert 8 / (M["C"] + 4 * M["H"]) == 0.5
    assert isclose(11.2 / M["Fe"] * VM, 4.48)
    assert isclose(200 * 0.15 / 300, 0.10)
    assert 2 ** ((50 - 20) / 10) == 8
    assert isclose(36 / M["C"] * 393, 1179)
    mass = round(1.931 * 29)
    assert mass == 56 and isclose(85.7 / 12 / 14.3, 0.5, abs_tol=0.005) and 4 * 12 + 8 == mass
    assert 4 / 40 == 0.1 and 9.8 / 98 == 0.1  # 1:1 NaOH:H₂SO₄ → NaHSO₄
    assert isclose(6.4 / M["Cu"] / 2 * VM, 1.12)
    # Task 2.1: 25 g CaCO₃ + excess HCl
    n = 25 / (M["Ca"] + M["C"] + 3 * M["O"])
    assert n == 0.25 and isclose(n * VM, 5.6)
    assert round(n * (M["Ca"] + 2 * M["Cl"])) == 28 and round(2 * n * (M["H"] + M["Cl"])) == 18


