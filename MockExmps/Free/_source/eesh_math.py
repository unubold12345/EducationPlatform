def checks() -> None:
    assert F(2, 3) + F(5, 6) - F(1, 4) == F(5, 4)
    assert 24000 / 0.8 == 30000
    assert F(2**3 * 4**2, 8**2) == 2
    assert sp.simplify(sp.log(54, 3) - sp.log(2, 3)) == 3
    sol = sp.solve([sp.Symbol("a") + 2 * sp.Symbol("b") - 7, 3 * sp.Symbol("a") - sp.Symbol("b") - 7])
    assert sol[sp.Symbol("a")] * sol[sp.Symbol("b")] == 6
    assert len([n for n in range(-20, 20) if n * n - 5 * n + 4 <= 0]) == 4
    d = (19 - 7) // 4
    a1 = 7 - 2 * d
    assert 10 * (2 * a1 + 9 * d) // 2 == 145
    assert 3 * (2**6 - 1) == 189
    alpha = sp.pi - sp.asin(sp.Rational(3, 5))
    assert sp.simplify(sp.tan(alpha)) == sp.Rational(-3, 4)
    roots = sp.solveset(2 * sp.cos(x) - 1, x, sp.Interval(0, 2 * sp.pi))
    assert sp.simplify(sum(roots)) == 2 * sp.pi
    assert sp.diff(x**3 - 3 * x**2 + 2, x).subs(x, 3) == 9
    assert F(6 * 8, 10) == F(24, 5)
    assert F(comb(4, 2), comb(10, 2)) == F(2, 15)
    assert sp.integrate(3 * x**2 - 2 * x + 1, (x, 0, 2)) == 6
    assert sp.sqrt(3**2 + 4**2) == 5  # slant height → lateral area π·3·5
    f17 = x**3 - 12 * x
    assert min(f17.subs(x, v) for v in [0, 2, 3]) == -16
    assert len([n for n in range(100, 1000) if len(set(str(n))) == 3 and set(str(n)) <= set("12345") and n % 2 == 0]) == 24
    # Task 2.1
    f = x**3 - 3 * x**2 - 9 * x + 5
    crit = sorted(sp.solve(sp.diff(f, x), x))
    assert crit == [-1, 3]
    assert f.subs(x, -1) == 10 and f.subs(x, 3) == -22
    assert sp.diff(f, x).subs(x, 0) == -9 and f.subs(x, 0) == 5
    # Task 2.2
    A, B, C = (1, 2), (5, 5), (4, -2)
    AB = (B[0] - A[0], B[1] - A[1])
    AC = (C[0] - A[0], C[1] - A[1])
    assert AB[0] ** 2 + AB[1] ** 2 == 25
    assert AB[0] * AC[0] + AB[1] * AC[1] == 0
    assert abs(AB[0] * AC[1] - AB[1] * AC[0]) / 2 == 12.5
    centre = ((B[0] + C[0]) / 2, (B[1] + C[1]) / 2)
    assert centre == (4.5, 1.5)
    assert isclose((B[0] - centre[0]) ** 2 + (B[1] - centre[1]) ** 2, 12.5)
    assert isclose((A[0] - centre[0]) ** 2 + (A[1] - centre[1]) ** 2, 12.5)


