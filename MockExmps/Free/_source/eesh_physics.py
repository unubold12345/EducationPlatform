    assert 12 / 4 == 3
    assert isclose(6 * 3 / (6 + 3) + 4, 6)
    assert 1100 / 220 == 5
    assert isclose(50 * (0.06 - 0.02) / 0.2, 10)
    assert isclose(2 * pi * sqrt(0.1 / 40), 0.314, abs_tol=0.001)
    assert isclose(50 * 6.8, 340)
    assert isclose(1 / (1 / 10 - 1 / 30), 15)
    assert (238 - 4, 92 - 2) == (234, 90)
    # Task 2.1: horizontal throw from 45 m at 40 m/s
    t = sqrt(2 * 45 / g)
    assert t == 3 and 40 * t == 120 and g * t == 30 and sqrt(40**2 + 30**2) == 50
    # Task 2.2: ε = 12 V, r = 1 Ω, R1 = 2 Ω, R2 = 3 Ω in series
    current = 12 / (1 + 2 + 3)
    assert current == 2 and current * 3 == 6 and current**2 * (2 + 3) * 10 == 200


